import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { applyBlockVisibility, hiddenDevices, writeHideOn } from "../../src/components/editor/inspector/visibility-model.ts";
import type { SiteDraft } from "../../src/lib/content-schema.ts";

test("hide on one device leaves the others visible, and all three sets hidden", () => {
  const mobile = writeHideOn({ hidden: false, hideOn: [] }, "mobile", true);
  assert.equal(mobile.hidden, false);
  assert.deepEqual(mobile.hideOn, ["mobile"]);
  assert.deepEqual(hiddenDevices(mobile), ["mobile"]);
  const tablet = writeHideOn(mobile, "tablet", true);
  const all = writeHideOn(tablet, "desktop", true);
  assert.equal(all.hidden, true);
  assert.deepEqual(all.hideOn, []);
  assert.deepEqual(hiddenDevices(all), ["desktop", "tablet", "mobile"]);
  const cleared = writeHideOn(all, "mobile", false);
  assert.equal(cleared.hidden, false);
  assert.deepEqual(cleared.hideOn, ["desktop", "tablet"]);
  const button = { id: "blk_button", kind: "button" as const, hidden: false, text: { text: "Button", marks: [] } };
  const site = { pages: [{ route: "/", sections: [{ id: "sec_1", type: "flow" as const, hidden: false, blocks: [button] }] }] } as unknown as SiteDraft;
  const next = applyBlockVisibility(site, "/", "sec_1", "blk_button", mobile);
  const updated = next.pages[0]?.sections[0];
  assert.equal(updated && updated.type === "flow" ? updated.blocks[0]?.hidden : true, false);
  assert.deepEqual(updated && updated.type === "flow" ? updated.blocks[0]?.hideOn : [], ["mobile"]);
  assert.equal(site.pages[0]?.sections[0] && site.pages[0].sections[0].type === "flow" ? site.pages[0].sections[0].blocks[0]?.hidden : true, false);
  const fields = readFileSync("src/components/editor/inspector/visibility-fields.tsx", "utf8");
  assert.equal(fields.includes("Hide on mobile"), true);
  assert.equal(fields.includes("Hide on desktop"), true);
  assert.equal(fields.includes("Hide on tablet"), true);
  const lowered = `${fields}\n${readFileSync("src/components/editor/inspector/visibility-model.ts", "utf8")}`.toLowerCase();
  assert.equal(lowered.includes("quantum"), false);
  assert.equal(lowered.includes("plum"), false);
  assert.equal(lowered.includes("hero"), false);
  const layers = readFileSync("src/components/editor/panels.tsx", "utf8");
  assert.equal(layers.includes("setLayerVisibility"), true);
  const layerVisibility = readFileSync("src/components/editor/layers/visibility-node.ts", "utf8");
  assert.equal(layerVisibility.includes("hideOn"), true);
});
