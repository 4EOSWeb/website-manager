import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import quantumAgeAdapter from "../../adapters/quantum-age/adapter.ts";
import { parseAdapter } from "../../src/platform/adapter/index.ts";
import { pageCapabilityFlags } from "../../src/components/editor/inspector/page-controls.ts";
import { articleBodyKind, isArticleRoute } from "../../src/platform/pages/route-flags.ts";

test("article routes use adapter flags instead of a blanket managed screen", () => {
  const parsed = parseAdapter(quantumAgeAdapter);
  assert.equal(parsed.ok, true);
  if (!parsed.ok) return;
  const adapter = parsed.value;
  const articleRoute = "/insights/keep-it-small";
  assert.equal(isArticleRoute(adapter, articleRoute), true);
  assert.equal(isArticleRoute(adapter, "/insights"), false);
  const article = pageCapabilityFlags(adapter, {}, articleRoute);
  assert.equal(article.providerManaged, false);
  assert.equal(article.editMetadata, true);
  assert.equal(article.editHeader, true);
  assert.equal(article.lockContent, false);
  assert.equal(articleBodyKind(adapter), "html-preserved");
  const privacy = pageCapabilityFlags(adapter, { locked: true }, "/privacy");
  assert.equal(privacy.providerManaged, true);
  assert.equal(privacy.editMetadata, true);
  assert.equal(privacy.editBody, false);
  const open = pageCapabilityFlags({ level: 2, pageCapabilities: { editBody: true }, articles: { enabled: true, routePattern: "/notes/:slug", body: "structured" }, routeCapabilities: { "/notes/:slug": { editMetadata: true, editHeader: true, providerManaged: false } } }, {}, "/notes/hello");
  assert.equal(open.providerManaged, false);
  assert.equal(open.editHeader, true);
  const shell = readFileSync("src/components/editor-shell.tsx", "utf8");
  assert.equal(shell.includes("/insights/"), false);
  assert.equal(shell.includes("isArticleRoute"), true);
  const scan = spawnSync("rg", ["/insights/", "src/components"], { encoding: "utf8" });
  assert.equal(scan.status, 1);
  const page = readFileSync("src/components/editor/inspector/page.tsx", "utf8");
  assert.equal(page.includes("This page is managed for you. You can still change its menu label and search details."), true);
  assert.equal(page.includes('data-article-region="metadata"'), true);
  assert.equal(page.includes('data-article-region="header"'), true);
  const platform = readFileSync("src/platform/pages/route-flags.ts", "utf8").toLowerCase();
  assert.equal(platform.includes("insights"), false);
  assert.equal(platform.includes("quantum"), false);
});
